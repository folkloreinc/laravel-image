<?php

declare(strict_types=1);

namespace Folklore\Image\Rendering;

use Imagick;
use ImagickException;
use Intervention\Image\Interfaces\ImageInterface;
use Jcupitt\Vips\Image as VipsImage;
use Jcupitt\Vips\Interpretation;

/**
 * Converts an image to sRGB from its embedded color profile, then removes the profile, so
 * browsers that ignore profiles show the right colors and derivatives don't carry it.
 *
 * Imagick and libvips convert with LittleCMS (relative colorimetric). GD has no color
 * management: it ignores profiles and keeps the stored values, as in 1.1.
 */
final class Srgb
{
    /**
     * A compact sRGB profile (ICC v4), generated by LittleCMS and dedicated to the public
     * domain (CC0).
     */
    public const string PROFILE = __DIR__.'/../../resources/icc/srgb.icc';

    /** The libvips interpretations that colourspace() converts to sRGB without a profile. */
    private const array VIPS_NON_RGB = [
        Interpretation::CMYK, Interpretation::LAB, Interpretation::LABQ, Interpretation::LABS, Interpretation::LCH,
        Interpretation::CMC, Interpretation::XYZ, Interpretation::YXY, Interpretation::HSV, Interpretation::SCRGB,
    ];

    /**
     * The embedded color profile of an image, read before edits that can drop it, for
     * convert(): with Imagick, Intervention's crop draws the image onto a new canvas, without
     * its profile. Null for other drivers, which keep it.
     */
    public static function profile(ImageInterface $image): ?string
    {
        $native = $image->core()->native();
        $icc = $native instanceof Imagick ? ($native->getImageProfiles('icc', true)['icc'] ?? null) : null;

        return is_string($icc) && $icc !== '' ? $icc : null;
    }

    /**
     * @param  string|null  $profile  the profile the image had before its edits (profile()), applied
     *                                when the image lost its own
     */
    public static function convert(ImageInterface $image, ?string $profile = null): ImageInterface
    {
        $native = $image->core()->native();

        if ($native instanceof Imagick) {
            if ($profile !== null && $native->getImageProfiles('icc', false) === []) {
                // Without a profile, setting one assigns it, without converting the pixels.
                try {
                    $native->profileImage('icc', $profile);
                } catch (ImagickException) {
                    // A profile LittleCMS can't read: the image keeps its stored values.
                }
            }
            self::convertImagick($native);
        } elseif ($native instanceof VipsImage) {
            $image->core()->setNative(self::convertVips($native));
        }

        return $image;
    }

    /**
     * An embedded profile that LittleCMS can't read (corrupt, or for another colorspace) is
     * dropped, and the stored values are kept, as GD does: a bad profile costs the color
     * conversion, not the image (#117).
     */
    private static function convertImagick(Imagick $imagick): void
    {
        if ($imagick->getImageProfiles('icc', false) !== []) {
            $profile = file_get_contents(self::PROFILE);
            if ($profile !== false) {
                try {
                    $imagick->profileImage('icc', $profile);
                } catch (ImagickException) {
                    // Imagick leaves the pixels as they were: removing the profile keeps them.
                }
            }
            $imagick->removeImageProfile('icc');
            if ($imagick->getImageColorspace() === Imagick::COLORSPACE_CMYK) {
                $imagick->transformImageColorspace(Imagick::COLORSPACE_SRGB);
            }
        } elseif ($imagick->getImageColorspace() === Imagick::COLORSPACE_CMYK) {
            $imagick->transformImageColorspace(Imagick::COLORSPACE_SRGB);
        }
    }

    private static function convertVips(VipsImage $image): VipsImage
    {
        if ($image->typeof('icc-profile-data') !== 0) {
            $image = $image->icc_transform(self::PROFILE, ['embedded' => true, 'intent' => 'relative']);
        } elseif (in_array($image->interpretation, self::VIPS_NON_RGB, true)) {
            $image = $image->colourspace(Interpretation::SRGB);
        }

        if ($image->typeof('icc-profile-data') !== 0) {
            $image = $image->copy();
            $image->remove('icc-profile-data');
        }

        return $image;
    }
}
